"""Grammar for a word-list entry from the Wiktionary subset
(wiktionary_extract.py). Nothing is generated by a general rule: every form
comes from Wiktionary. The only exception is the small, fixed list of
conjunction types below. Anything ambiguous is returned with a review reason.

Result: (part_of_speech, grammar dict, ipa, reasons)."""

import re

from app.scripts.woerterbuch.source import Entry

POS_LABEL = {
    "noun": "Nomen", "verb": "Verb", "adj": "Adjektiv", "adv": "Adverb", "prep": "Präposition",
    "conj": "Konjunktion", "pron": "Pronomen", "particle": "Partikel", "intj": "Interjektion",
    "num": "Numerale", "det": "Artikelwort", "article": "Artikelwort", "phrase": "Wendung",
    "prep_phrase": "Wendung", "adv_phrase": "Wendung", "contraction": "Präposition", "name": "Eigenname",
}
GENDER_ARTICLE = {"m": "der", "f": "die", "n": "das"}

# Conjunction types are a closed class: the word order rule is fixed grammar.
SUBORDINATING = {"dass", "weil", "obwohl", "obgleich", "obschon", "wenn", "als", "ob", "damit", "während", "bevor",
                 "nachdem", "seit", "seitdem", "bis", "sobald", "solange", "falls", "sofern", "sodass", "indem",
                 "ehe", "wohingegen", "wobei", "da", "zumal", "soweit", "sowie", "anstatt dass", "ohne dass",
                 "so dass", "als ob", "wie", "je", "insofern", "insoweit", "unter der Voraussetzung, dass"}
COORDINATING = {"und", "oder", "aber", "denn", "sondern", "doch", "sowie"}
TWO_PART = {"entweder ... oder", "weder ... noch", "sowohl ... als auch", "nicht nur ... sondern auch", "je ... desto",
            "zwar ... aber", "einerseits ... andererseits"}
ADVERB_CONNECTORS = {"deshalb", "deswegen", "darum", "daher", "trotzdem", "dennoch", "außerdem", "folglich",
                     "somit", "also", "dann", "danach", "sonst", "allerdings", "jedoch", "infolgedessen",
                     "demzufolge", "demnach", "dementsprechend", "nichtsdestotrotz", "hingegen", "andernfalls",
                     "stattdessen", "zudem", "ebenso", "anschließend", "schließlich", "inzwischen"}

PERSONS = (("ich", ("first-person", "singular")), ("du", ("second-person", "singular")),
           ("er/sie/es", ("third-person", "singular")), ("wir", ("first-person", "plural")),
           ("ihr", ("second-person", "plural")), ("sie/Sie", ("third-person", "plural")))
REFLEXIVE_ACC = ("mich", "dich", "sich", "uns", "euch", "sich")
POS_PREFERENCE = ("noun", "verb", "adj", "prep", "conj", "adv", "pron", "particle", "det", "num", "intj",
                  "phrase", "prep_phrase", "adv_phrase", "contraction", "name")


def _forms(entry: dict, *tags: str, exclude: tuple[str, ...] = ()) -> list[str]:
    out = []
    for f in entry["forms"]:
        t = set(f["tags"])
        if set(tags) <= t and not t & set(exclude) and f["form"] not in out:
            out.append(f["form"])
    return out


def head_genders(word: str, head: str) -> list[str]:
    """Genders written right after the headword: 'Vater m (strong, …
    diminutive Väterchen n)' -> ['m'] (the diminutive's n is not the word's);
    'Joghurt m or n (…)' -> ['m', 'n']; 'Leute pl (…)' -> ['pl']."""
    if not head.startswith(word):
        return []
    m = re.match(r"^\s*((?:m|f|n|pl)(?:\s+or\s+(?:m|f|n|pl))*)(?=[\s(,]|$)", head[len(word):])
    return re.findall(r"m|f|n|pl", m.group(1)) if m else []


def _gender(e: dict) -> str | None:
    for head in e["head"]:
        g = head_genders(e["word"], head)
        if g:
            return g[0]
    return None


def _choose(entry: Entry, candidates: list[dict], reasons: list[str]) -> dict | None:
    real = [c for c in candidates if "form-of" not in c["sense_tags"] and "alt-of" not in c["sense_tags"]] or candidates
    if not real:
        return None
    if entry.article:
        nouns = [c for c in real if c["pos"] == "noun"]
        if not nouns:
            reasons.append("pos:article_but_no_wiktionary_noun")
            return None
        matching = [c for c in nouns if entry.article in
                    {GENDER_ARTICLE.get(g) for h in c["head"] for g in head_genders(c["word"], h)}]
        if not matching and entry.article == "die":
            matching = [c for c in nouns if "plural-only" in c["sense_tags"]
                        or any("pl" in head_genders(c["word"], h) for h in c["head"])]
        if not matching:
            reasons.append("grammar:article_differs_from_wiktionary")
            return nouns[0]
        return matching[0]
    by_pos = {}
    for c in real:
        by_pos.setdefault(c["pos"], c)
    translations = " ".join(entry.translations()).lower()
    if entry.reflexive or (translations.endswith("moq") and "verb" in by_pos):
        if "verb" in by_pos:
            return by_pos["verb"]
    non_noun = [p for p in POS_PREFERENCE if p in by_pos and p != "noun"]
    if not non_noun:
        reasons.append("pos:only_noun_but_no_article")
        return None
    # an adjective that is also listed as an adverb is the normal German case
    if len(non_noun) > 1 and set(non_noun) != {"adj", "adv"}:
        reasons.append("pos:alternatives_" + "+".join(non_noun))
    if non_noun[0] == "verb" and not translations.endswith("moq") and "adj" in by_pos:
        return by_pos["adj"]
    return by_pos[non_noun[0]]


def _noun(c: dict, entry: Entry, reasons: list[str]) -> dict:
    head = " ".join(c["head"])
    if _gender(c) == "pl":
        # die Ferien, die Leute: only a plural exists
        return {"article": "die", "number": "Pluraletantum", "singular": None, "plural": f"die {entry.lemma}"}
    if "adjectival" in head:
        # der Angestellte -> die Angestellten (weak plural after the article)
        m = re.search(r"definite plural die (\S+?)[,)]", head)
        if m:
            return {"article": entry.article, "gender": _gender(c), "singular": entry.lemma,
                    "plural": f"die {m.group(1)}", "genitive": None, "note": "substantiviertes Adjektiv"}
    plural = [f["form"] for f in c["forms"] if f["tags"] == ["plural"]] \
        or _forms(c, "plural", "nominative", exclude=("definite", "indefinite"))
    plural = [p for p in plural if p not in ("-", "—")]
    uncountable = "uncountable" in c["sense_tags"] or any("no plural" in h or "uncountable" in h for h in c["head"])
    g = {"article": entry.article, "gender": _gender(c), "singular": entry.lemma,
         "plural": f"die {plural[0]}" if plural else None, "genitive": next(iter(_forms(c, "genitive", "singular")), None)}
    if not plural:
        g["plural_note"] = "kein Plural" if uncountable else None
        if not uncountable:
            reasons.append("grammar:plural_not_found")
    if len(plural) > 1:
        g["plural_variants"] = [f"die {p}" for p in plural[1:]]
    return g


def _verb(c: dict, entry: Entry, reasons: list[str]) -> dict:
    present = []
    for i, (person, tags) in enumerate(PERSONS):
        form = next(iter(_forms(c, "present", "indicative", *tags, exclude=("subjunctive",))), None)
        if form is None:
            reasons.append("grammar:present_incomplete")
            present = []
            break
        if entry.reflexive:
            words = form.split(" ")
            form = " ".join([words[0], REFLEXIVE_ACC[i], *words[1:]])
        present.append({"person": person, "form": form})
    preterite = next(iter(_forms(c, "preterite", "third-person", "singular", "indicative")), None) \
        or next(iter([f["form"] for f in c["forms"] if f["tags"] == ["past"]]), None)
    participle = next(iter(_forms(c, "participle", "past")), None)
    aux = [a for a in _forms(c, "auxiliary") if a in ("haben", "sein")]
    head = " ".join(c["head"])
    kind = next((k for k in ("irregular strong", "strong", "weak", "mixed", "irregular") if f"({k}" in head or f" {k}," in head), None)
    # "steht auf": a separable verb's finite form is two words in Wiktionary
    sep_forms = _forms(c, "present", "indicative", "third-person", "singular", exclude=("subjunctive",))
    separable = (" " in sep_forms[0]) if sep_forms else None
    if not preterite:
        reasons.append("grammar:preterite_not_found")
    if not participle:
        reasons.append("grammar:participle_not_found")
    if not aux:
        reasons.append("grammar:auxiliary_not_found")
    if len(aux) > 1:
        reasons.append("grammar:auxiliary_haben_or_sein")
    if entry.reflexive:
        reasons.append("grammar:reflexive_pronoun_accusative_assumed")
    perfect = None
    if participle and len(aux) == 1:
        perfect = ("hat" if aux[0] == "haben" else "ist") + (" sich " if entry.reflexive else " ") + participle
    return {"infinitive": ("sich " if entry.reflexive else "") + entry.lemma, "reflexive": entry.reflexive,
            "conjugation_type": {"weak": "schwach", "strong": "stark", "irregular strong": "stark (unregelmäßig)",
                                 "mixed": "gemischt", "irregular": "unregelmäßig"}.get(kind),
            "separable": separable, "praeteritum": preterite, "partizip_ii": participle, "auxiliary": aux or None,
            "perfekt": perfect, "praesens": present or None}


def _adj(c: dict, entry: Entry, reasons: list[str]) -> dict:
    comp = next(iter(_forms(c, "comparative", exclude=("nominative", "genitive", "dative", "accusative", "strong", "weak", "mixed"))), None)
    sup = next(iter(_forms(c, "superlative", exclude=("nominative", "genitive", "dative", "accusative", "strong", "weak", "mixed"))), None)
    head = " ".join(c["head"])
    not_comparable = "not comparable" in head or (comp is None and sup is None and "comparative" not in head)
    if comp is None and not not_comparable:
        reasons.append("grammar:comparative_not_found")
    return {"positiv": entry.lemma, "komparativ": comp, "superlativ": sup,
            "note": "nicht steigerbar" if not_comparable and comp is None else None}


def _prep(c: dict, reasons: list[str]) -> dict:
    head = " ".join(c["head"]).lower() + " " + " ".join(c["glosses"]).lower()
    cases = [k for k, label in (("akkusativ", "accusative"), ("dativ", "dative"), ("genitiv", "genitive")) if f"+ {label}" in head or f"{label}" in head.split("(+")[-1]]
    if not cases:
        reasons.append("grammar:case_government_not_found")
    return {"cases": [{"akkusativ": "Akkusativ", "dativ": "Dativ", "genitiv": "Genitiv"}[k] for k in cases] or None,
            "wechselpraeposition": cases == ["akkusativ", "dativ"] or None}


def conjunction_rule(lemma: str) -> dict | None:
    low = lemma.lower()
    if low in TWO_PART:
        return {"type": "zweiteilig", "word_order": "zweiteilige Konjunktion"}
    if low in SUBORDINATING:
        return {"type": "subordinierend", "word_order": "Nebensatz: das konjugierte Verb steht am Ende"}
    if low in COORDINATING:
        return {"type": "koordinierend", "word_order": "Position 0: keine Änderung der Wortstellung"}
    if low in ADVERB_CONNECTORS:
        return {"type": "Konjunktionaladverb", "word_order": "Position 1: das Verb folgt direkt (Inversion)"}
    return None


_PLURALS: dict[int, dict] = {}


def _plural_map(nouns: dict) -> dict:
    """plural -> singular for every Wiktionary noun whose plural differs."""
    if id(nouns) not in _PLURALS:
        best: dict[str, str] = {}
        # several singulars can share a plural (Ergebnis / old Ergebniss):
        # a normal entry beats form-of, the shorter beats the longer, no ß beats ß
        rank = lambda w: (bool(nouns[w][2]), len(w), "ß" in w)  # noqa: E731
        for word, row in nouns.items():
            if row[1] and row[1] != word and (row[1] not in best or rank(word) < rank(best[row[1]])):
                best[row[1]] = word
        _PLURALS[id(nouns)] = best
    return _PLURALS[id(nouns)]


def compound_noun(entry: Entry, nouns: dict) -> tuple[dict, str] | None:
    """A German compound noun takes gender and plural from its last part
    (der Fahrrad|helm -> Helm m, plural Helme -> die Fahrradhelme). The
    longest Wiktionary noun that ends the word and has the entry's gender wins."""
    word = entry.lemma
    if " " in word:
        return None
    plurals = _plural_map(nouns)
    for i in range(0, len(word) - 2):
        part = word[i:].capitalize()
        prefix = word[:i]
        # the word list gives some nouns in the plural: die (Forschungs)ergebnisse
        singular = plurals.get(part)
        if singular and entry.article == "die" and (part not in nouns or nouns[part][2]):
            s_genders = head_genders(singular, nouns[singular][0])
            s_article = next((GENDER_ARTICLE[g] for g in s_genders if g in GENDER_ARTICLE), None)
            return {"article": "die", "number": "Plural", "plural": f"die {word}",
                    "singular": f"{s_article} {prefix}{singular.lower() if prefix else singular}" if s_article else None,
                    "compound_head": singular if prefix else None}, singular
        if i == 0:
            continue
        row = nouns.get(part)
        if not row:
            continue
        head, plural = row[0], row[1]
        genders = head_genders(part, head)
        if entry.article not in {GENDER_ARTICLE.get(g) for g in genders}:
            continue
        prefix = word[:i]
        grammar = {"article": entry.article, "gender": next(g for g in genders if GENDER_ARTICLE.get(g) == entry.article),
                   "singular": word, "plural": f"die {prefix}{plural.lower() if plural else ''}" if plural and plural != "-" else None,
                   "compound_head": part}
        return grammar, part
    return None


def resolve(entry: Entry, subset: dict, nouns: dict | None = None) -> tuple[str | None, dict | None, str | None, str, list[str]]:
    """-> (part_of_speech label, grammar, ipa, grammar_source, reasons)"""
    reasons: list[str] = []
    candidates = list(subset.get(entry.lemma, []))
    if entry.reflexive:
        candidates = list(subset.get("sich " + entry.lemma, [])) + candidates
    if entry.german != entry.lemma:
        candidates += subset.get(entry.german, [])
    rule = conjunction_rule(entry.lemma)
    rule_pos = None if not rule else ("Adverb" if rule["type"] == "Konjunktionaladverb" else "Konjunktion")
    chosen = _choose(entry, candidates, reasons) if candidates else None
    if "grammar:article_differs_from_wiktionary" in reasons and nouns:
        # "die Sprachkenntnisse": not a feminine singular but a plural
        found = compound_noun(entry, nouns)
        if found and found[0].get("number") == "Plural":
            reasons.remove("grammar:article_differs_from_wiktionary")
            return "Nomen", found[0], chosen["ipa"] if chosen else None, "wiktionary_compound", reasons + ["grammar:listed_in_plural"]
    if chosen is None and entry.article and nouns:
        found = compound_noun(entry, nouns)
        if found:
            grammar, part = found
            if not grammar["plural"]:
                reasons.append("grammar:plural_not_found")
            reasons = [r for r in reasons if not r.startswith("pos:article_but") and r != "grammar:not_in_wiktionary"]
            if grammar.get("number") == "Plural":
                reasons.append("grammar:listed_in_plural")
            if grammar.get("compound_head"):
                reasons.append("grammar:compound_derived_from_" + part)
            return "Nomen", grammar, None, "wiktionary_compound", reasons
    if chosen is None:
        if rule:
            return rule_pos, {"conjunction": rule}, None, "rule", []
        if not candidates:
            reasons.append("grammar:not_in_wiktionary")
        if entry.article:
            return "Nomen", {"article": entry.article, "singular": entry.lemma, "plural": None}, None, "none", reasons
        if entry.reflexive:
            return "Verb", None, None, "none", reasons
        return ("Wendung" if " " in entry.lemma else None), None, None, "none", reasons
    pos = chosen["pos"]
    if pos == "verb" and "form-of" in chosen["sense_tags"]:
        m = re.match(r"past participle of (\S+)", (chosen["glosses"] or [""])[0])
        if m and not " ".join(entry.translations()).endswith("moq"):
            # genervt, überfordert …: a participle used as an adjective
            return "Adjektiv", {"positiv": entry.lemma, "partizip_ii_von": m.group(1), "note": "Partizip II als Adjektiv",
                                "komparativ": None, "superlativ": None}, chosen["ipa"], "wiktionary", \
                reasons + ["grammar:participle_adjective_no_comparison"]
    if pos == "noun":
        grammar = _noun(chosen, entry, reasons)
    elif pos == "verb":
        grammar = _verb(chosen, entry, reasons)
    elif pos == "adj":
        grammar = _adj(chosen, entry, reasons)
    elif pos in ("prep", "contraction"):
        grammar = _prep(chosen, reasons)
    else:
        grammar = {}
    label = POS_LABEL.get(pos, pos)
    if rule and pos in ("conj", "adv"):
        grammar["conjunction"] = rule
        label = rule_pos
        reasons = [r for r in reasons if not r.startswith("pos:alternatives_conj+adv")]
    gloss = chosen["glosses"][:3]
    if gloss:
        grammar["gloss_en"] = gloss
    return label, grammar, chosen["ipa"], "wiktionary", reasons
